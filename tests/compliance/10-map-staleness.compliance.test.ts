/**
 * Compliance: spec v0.3 section 4.4 — the map/ codebase store and its staleness contract
 * - map nodes MUST have type: file and a path field
 * - ambient capture MUST flag map nodes stale when a commit touches their path (16.1 step 4)
 * - inject MUST render stale map nodes with a visible (stale) marker
 * - implementations MUST NOT serve stale map content as authoritative
 *
 * "A stale map entry is worse than no entry" is the whole point of this suite:
 * every test here exists to stop the map confidently lying to an agent.
 */
import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import { mkdtemp, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import {
  commitNode,
  makeMapNode,
  markStaleByPaths,
  refreshMapNode,
  readMapEntries,
  pathIsCovered,
  inject,
  readNode,
  readMemoryMap,
  writeMemoryMap,
  createEmptyMemoryMap,
  writeAgentsConfig,
  createDefaultAgentsConfig,
  validate,
} from '@mastishk/core';
import type { MskNode } from '@mastishk/core';

let tmpDir: string;
let mastishkDir: string;

beforeEach(async () => {
  tmpDir = await mkdtemp(join(tmpdir(), 'msk-c10-'));
  mastishkDir = join(tmpDir, '.mastishk');
  await writeMemoryMap(join(mastishkDir, 'memory-map.json'), createEmptyMemoryMap());
  await writeAgentsConfig(mastishkDir, createDefaultAgentsConfig());
});
afterEach(async () => {
  await rm(tmpDir, { recursive: true, force: true });
});

function mapNode(id: string, path: string, body = 'Signs and verifies JWTs.'): MskNode {
  return makeMapNode(id, path, body, { created_by: 'claude-code', last_updated_by: 'claude-code' });
}

// ---------------------------------------------------------------------------
// Section 4.4 — map node shape
// ---------------------------------------------------------------------------

describe('section 4.4 — map node requirements', () => {
  it('a map node MUST have type: file', () => {
    expect(mapNode('map-auth', 'src/auth.ts').type).toBe('file');
  });

  it('a map node without a path MUST be rejected', () => {
    const bad = { ...mapNode('map-auth', 'src/auth.ts') };
    delete (bad as Partial<MskNode>).path;
    const result = validate(bad);
    expect(result.valid).toBe(false);
    expect(result.errors.join(' ')).toMatch(/path/);
  });

  it('a map node with a non-file type MUST be rejected', () => {
    const bad = { ...mapNode('map-auth', 'src/auth.ts'), type: 'fact' as const };
    expect(validate(bad).valid).toBe(false);
  });

  it('map nodes generated by scan carry confidence 0.6 and scanned: true', () => {
    const node = mapNode('map-auth', 'src/auth.ts');
    expect(node.confidence).toBe(0.6);
    expect(node.scanned).toBe(true);
  });
});

// ---------------------------------------------------------------------------
// Section 4.4 + 16.1 step 4 — the staleness contract
// ---------------------------------------------------------------------------

describe('section 16.1 step 4 — staleness flagging', () => {
  it('a changed path MUST flag the map node covering it', async () => {
    await commitNode(mastishkDir, mapNode('map-auth', 'src/auth/token.ts'));
    await markStaleByPaths(mastishkDir, ['src/auth/token.ts']);
    expect((await readNode(join(mastishkDir, 'map', 'map-auth.msk.md'))).stale).toBe(true);
  });

  it('a changed file MUST flag a map node covering its directory', async () => {
    await commitNode(mastishkDir, mapNode('map-auth-dir', 'src/auth'));
    await markStaleByPaths(mastishkDir, ['src/auth/token.ts']);
    expect((await readNode(join(mastishkDir, 'map', 'map-auth-dir.msk.md'))).stale).toBe(true);
  });

  it('path matching MUST respect segment boundaries', () => {
    // Flagging src/authz when only src/auth is mapped would stale the wrong entry;
    // NOT flagging src/auth/token.ts when src/auth is mapped would miss a real one.
    expect(pathIsCovered('src/auth', 'src/authz/policy.ts')).toBe(false);
    expect(pathIsCovered('src/auth', 'src/auth/token.ts')).toBe(true);
  });

  it('an unrelated commit MUST NOT flag a map node', async () => {
    await commitNode(mastishkDir, mapNode('map-auth', 'src/auth/token.ts'));
    await markStaleByPaths(mastishkDir, ['docs/README.md']);
    expect((await readNode(join(mastishkDir, 'map', 'map-auth.msk.md'))).stale).toBe(false);
  });

  it('the stale flag MUST be visible in the graph index, not only the node file', async () => {
    await commitNode(mastishkDir, mapNode('map-auth', 'src/auth/token.ts'));
    await markStaleByPaths(mastishkDir, ['src/auth/token.ts']);
    const map = await readMemoryMap(join(mastishkDir, 'memory-map.json'));
    expect(map.nodes['map-auth']!.stale).toBe(true);
  });

  it('an agent MUST be able to clear the flag after verifying the entry', async () => {
    await commitNode(mastishkDir, mapNode('map-auth', 'src/auth/token.ts'));
    await markStaleByPaths(mastishkDir, ['src/auth/token.ts']);
    expect(await refreshMapNode(mastishkDir, 'map-auth')).toBe(true);
    expect((await readNode(join(mastishkDir, 'map', 'map-auth.msk.md'))).stale).toBe(false);
  });
});

// ---------------------------------------------------------------------------
// Section 6.4 — stale entries MUST be visibly marked wherever they surface
// ---------------------------------------------------------------------------

describe('section 6.4 — stale map entries in inject output', () => {
  it('inject renders matched map nodes under a Codebase map section', async () => {
    await commitNode(mastishkDir, mapNode('map-auth', 'src/auth/token.ts', 'Handles jwt signing.'));
    const out = await inject('jwt signing', mastishkDir);
    expect(out).toContain('Codebase map');
    expect(out).toContain('map-auth');
  });

  it('a stale map node MUST be rendered with a (stale) marker', async () => {
    await commitNode(mastishkDir, mapNode('map-auth', 'src/auth/token.ts', 'Handles jwt signing.'));
    await markStaleByPaths(mastishkDir, ['src/auth/token.ts']);

    const out = await inject('jwt signing', mastishkDir);
    expect(out).toContain('(stale)');
  });

  it('a fresh map node MUST NOT be marked stale', async () => {
    await commitNode(mastishkDir, mapNode('map-auth', 'src/auth/token.ts', 'Handles jwt signing.'));
    const out = await inject('jwt signing', mastishkDir);
    expect(out).not.toContain('(stale)');
  });

  it('refreshing a stale entry removes the marker from inject output', async () => {
    await commitNode(mastishkDir, mapNode('map-auth', 'src/auth/token.ts', 'Handles jwt signing.'));
    await markStaleByPaths(mastishkDir, ['src/auth/token.ts']);
    await refreshMapNode(mastishkDir, 'map-auth');

    const out = await inject('jwt signing', mastishkDir);
    expect(out).not.toContain('(stale)');
  });
});

// ---------------------------------------------------------------------------
// Map inspection surface
// ---------------------------------------------------------------------------

describe('section 11 — map inspection', () => {
  it('stale entries are separable from fresh ones', async () => {
    await commitNode(mastishkDir, mapNode('map-a', 'src/a.ts'));
    await commitNode(mastishkDir, mapNode('map-b', 'src/b.ts'));
    await markStaleByPaths(mastishkDir, ['src/b.ts']);

    const stale = (await readMapEntries(mastishkDir)).filter((e) => e.stale);
    expect(stale.map((e) => e.id)).toEqual(['map-b']);
  });

  it('map entries expose the path they describe', async () => {
    await commitNode(mastishkDir, mapNode('map-a', 'src/a.ts'));
    const entries = await readMapEntries(mastishkDir);
    expect(entries[0]!.path).toBe('src/a.ts');
  });
});
